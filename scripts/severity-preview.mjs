// Local-only harness: real Worker, real sync, isolated D1, mocked GitHub boundary.
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
import { createServer } from 'node:http';
import { readFile, readdir } from 'node:fs/promises';
import { dirname, extname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fixtures, githubResponse } from './severity-fixtures.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const moduleRoot=resolve(root,'dist-worker');
const runtime=new Miniflare(convertV4MiniflareOptions({
  modules:[{type:'ESModule',path:resolve(moduleRoot,'local-preview.js'),contents:`
    import worker from './index.js';
    import { runSyncOneRepo } from './sync.js';
    export default { async fetch(request,env,ctx) {
      if(new URL(request.url).pathname==='/__bootstrap') {
        for(let i=0;i<100;i++) {
          const result=await runSyncOneRepo(env,{deferFinalization:true});
          if(!result.ok) throw new Error(result.message);
          if(result.done) return Response.json({ok:true});
        }
        throw new Error('Synthetic sync exceeded budget');
      }
      return worker.fetch(request,env,ctx);
    }};`},
    ...(await readdir(moduleRoot,{recursive:true})).filter(n=>n.endsWith('.js')).map(n=>({type:'ESModule',path:resolve(moduleRoot,n)}))],
  modulesRoot:moduleRoot,compatibilityDate:'2026-06-10',d1Databases:['DB'],kvNamespaces:['RATE_KV'],
  bindings:{ENVIRONMENT:'development',GITHUB_TOKEN:'synthetic-local-only'},
  outboundService:request=>{
    try {const url=new URL(request.url);if(url.hostname!=='api.github.com'||request.method!=='GET') throw new Error();return Response.json(githubResponse(url));}
    catch {return new Response('Outbound request blocked by local fixture harness',{status:503});}
  },
}));
const db=await runtime.getD1Database('DB');
for(const statement of (await readFile(resolve(root,'schema.sql'),'utf8')).replace(/--[^\n]*/g,'').split(';').map(s=>s.trim()).filter(Boolean)) await db.prepare(statement).run();
const boot=await runtime.dispatchFetch('http://localhost/__bootstrap');
if(!boot.ok) throw new Error('Local sync bootstrap failed: '+await boot.text());
// Assert the database values generated by real sync, rather than seed them.
for(const fixture of fixtures) {
  const stored=await db.prepare('SELECT severity FROM pull_requests WHERE id=?').bind(fixture.id).first();
  if(stored?.severity!==fixture.expected) throw new Error(`Unexpected synced severity for fixture ${fixture.id}`);
  const detail=await (await runtime.dispatchFetch(`http://localhost/api/pr-panel/${fixture.id}/details`)).json();
  const expectedSource=fixture.repoId===97001 && fixture.number<=2 ? 'findings' : 'tldr';
  if(detail.tldr_source!==expectedSource || !detail.tldr || detail.tldr.includes('## What we found')) throw new Error(`Unexpected review brief for fixture ${fixture.id}`);
}
console.log(`Verified ${fixtures.length} synthetic PRs through real sync.`);
const types={'.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.woff2':'font/woff2','.woff':'font/woff','.png':'image/png','.html':'text/html'};
const server=createServer(async(req,res)=>{
  try {
    const url=new URL(req.url,'http://localhost:8791');
    if(!['GET','HEAD'].includes(req.method)){res.writeHead(405);res.end('Read-only local preview');return;}
    if(url.pathname==='/__local/avatar.svg'){res.writeHead(200,{'content-type':'image/svg+xml'});res.end('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" fill="#1870b8"/></svg>');return;}
    if(url.pathname.startsWith('/api/')) {
      const response=await runtime.dispatchFetch(url.href,{headers:req.headers});
      res.writeHead(response.status,{'content-type':'application/json','cache-control':'no-store'});res.end(Buffer.from(await response.arrayBuffer()));return;
    }
    const dist=resolve(root,'dist'), filename=resolve(dist,'.'+decodeURIComponent(url.pathname));
    if(!filename.startsWith(dist+sep)){res.writeHead(403);res.end();return;}
    let bytes,html=false;try {bytes=await readFile(filename);}catch {bytes=await readFile(resolve(dist,'index.html'));html=true;}
    if(html) bytes=Buffer.from(bytes.toString().replace('<body>','<body><aside style="padding:10px;background:#fff6da;font:13px system-ui">LOCAL SEVERITY REVIEW · synthetic AppSecAI report formats · real sync and API handlers · <a href="/workspace/fixes?layout=table&all=1">All fixes</a> · <a href="/workspace/fixes?layout=table&all=1&severity=medium">Medium</a> · <a href="/workspace/fixes?layout=table&all=1&severity=high">High</a> · <a href="/workspace/fixes?layout=table&all=1&severity=unknown">Unknown</a></aside>'));
    res.writeHead(200,{'content-type':html?'text/html':types[extname(filename)]||'application/octet-stream','cache-control':'no-store'});res.end(bytes);
  } catch(error){console.error(error);res.writeHead(500);res.end('Local harness failed');}
});
server.listen(8791,'127.0.0.1',()=>console.log('Local severity review: http://localhost:8791/workspace/fixes?layout=table&all=1'));
for(const signal of ['SIGINT','SIGTERM']) process.on(signal,async()=>{server.close();await runtime.dispose();process.exit(0);});
